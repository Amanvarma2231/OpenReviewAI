"""
Enhanced Markdown Audit Report Exporter for OpenReviewAI.
Generates a professional, detailed audit trail with full metrics,
bug breakdown, diff, and executive summary.
"""
from datetime import datetime
from typing import Optional
from openreview_ai.schema import WorkflowResult
from openreview_ai.utils.diff_viewer import compute_unified_diff


def export_markdown_report(result: WorkflowResult) -> str:
    """
    Generates a complete, professional markdown audit report of the
    multi-LLM review workflow. Suitable for submission, archiving,
    or including in documentation.
    """
    now   = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines = []

    # ── Header ──────────────────────────────────────────────────
    lines += [
        "# 🛡️ OpenReviewAI — Multi-LLM Code Review Audit Report",
        "",
        "> Auto-generated by OpenReviewAI v1.0.0 · Druidot Consulting Pvt. Ltd.",
        "",
        f"| Field            | Value |",
        f"| :---             | :--- |",
        f"| **Generated At** | `{now}` |",
        f"| **Final Status** | `{result.status}` |",
        f"| **Provider**     | `{result.provider}` |",
        f"| **Language**     | `{result.target_language}` |",
        f"| **Rounds**       | `{result.rounds_count}` |",
        f"| **Bugs Detected** | `{result.total_bugs_detected}` |",
        f"| **Bugs Resolved** | `{result.total_bugs_fixed}` |",
        "",
    ]

    # ── LLM Architecture ────────────────────────────────────────
    lines += [
        "## 🤖 Multi-LLM Agent Architecture",
        "",
        "| # | Agent Role | Model | Responsibility |",
        "| :- | :--- | :--- | :--- |",
        f"| 1 | **Code Generator & Fixer** | `{result.generator_model}` | Writes initial code; applies targeted iterative fixes from reviewer feedback |",
        f"| 2 | **Code Reviewer & Inspector** | `{result.reviewer_model}` | Static/semantic analysis; flags bugs by severity and category |",
    ]
    if result.validator_model:
        lines.append(f"| 3 | **Security & QA Validator** | `{result.validator_model}` | Security audit (CWE checks), consensus arbiter, final approval |")
    lines.append("")

    # ── Sandbox Execution Summary ────────────────────────────────
    if result.final_execution:
        fe = result.final_execution
        lines += [
            "## ⚡ Sandbox Execution Summary",
            "",
            f"| Metric | Value |",
            f"| :--- | :--- |",
            f"| **Success** | `{'✅ Yes' if fe.success else '❌ No'}` |",
            f"| **Exit Code** | `{fe.exit_code}` |",
            f"| **Runtime** | `{fe.execution_time_ms:.1f} ms` |",
            f"| **Syntax Valid** | `{'✅ Yes' if fe.syntax_valid else '❌ No'}` |",
            "",
        ]
        if fe.stdout.strip():
            lines += ["**stdout:**", "```", fe.stdout.strip(), "```", ""]
        if fe.stderr.strip():
            lines += ["**stderr:**", "```", fe.stderr.strip(), "```", ""]

    # ── Task Specification ───────────────────────────────────────
    lines += [
        "## 📋 Task Specification",
        "",
        "```text",
        result.task_prompt.strip(),
        "```",
        "",
    ]

    # ── Iteration History ────────────────────────────────────────
    lines += [
        "## 🔄 Iteration & Agent Communication History",
        "",
    ]
    for step in result.iterations:
        status_icon = "✅" if step.status == "APPROVED" else "🔄"
        lines.append(f"### Round {step.round_idx} — {status_icon} {step.status}")
        lines.append("")

        if step.generator_explanation:
            lines += [
                "**LLM 1 — Generator/Fixer Response:**",
                f"> {step.generator_explanation.strip()}",
                "",
            ]

        if step.execution:
            exec_icon = "✅" if step.execution.success else "❌"
            lines.append(
                f"**Sandbox Verification:** {exec_icon} Exit `{step.execution.exit_code}` "
                f"· Runtime `{step.execution.execution_time_ms:.1f}ms`"
            )
            if step.execution.syntax_error:
                lines.append(f"> ⚠️ Syntax Error: `{step.execution.syntax_error}`")
            if step.execution.stderr.strip():
                lines += ["```", step.execution.stderr.strip(), "```"]
            lines.append("")

        lines.append("**Reviewer Evaluations:**")
        lines.append("")
        for rev in step.reviews:
            s_icon = "🟢" if rev.status == "APPROVED" else "🔴"
            lines += [
                f"**{rev.reviewer_name}** (`{rev.reviewer_model}`): {s_icon} `{rev.status}` — Score: **{rev.overall_score}/10**",
                f"*{rev.summary}*",
                "",
            ]
            if rev.bugs:
                lines.append(f"*Bugs identified ({len(rev.bugs)}):*")
                lines.append("")
                for bug in rev.bugs:
                    line_ref  = f"Line {bug.line_number}: " if bug.line_number else ""
                    res_icon  = "✅" if bug.resolved else "🔴"
                    lines.append(
                        f"- {res_icon} `[{bug.severity}]` `[{bug.category}]` "
                        f"{line_ref}**{bug.description}**  \n"
                        f"  *Suggested Fix:* `{bug.suggested_fix}`"
                    )
                lines.append("")

        lines.append("---")
        lines.append("")

    # ── Bug Breakdown Table ──────────────────────────────────────
    all_bugs = [b for step in result.iterations for r in step.reviews for b in r.bugs]
    if all_bugs:
        lines += [
            "## 🐛 Complete Bug Registry",
            "",
            "| # | Round | Severity | Category | Description | Resolved |",
            "| :- | :- | :--- | :--- | :--- | :- |",
        ]
        for i, bug in enumerate(all_bugs, 1):
            # Find the round this bug came from
            bug_round = "?"
            for step in result.iterations:
                for r in step.reviews:
                    if bug in r.bugs:
                        bug_round = str(step.round_idx)
            res_icon = "✅" if bug.resolved else "❌"
            lines.append(
                f"| {i} | {bug_round} | `{bug.severity}` | `{bug.category}` "
                f"| {bug.description[:80]} | {res_icon} |"
            )
        lines.append("")

    # ── Code Evolution Diff ──────────────────────────────────────
    if len(result.iterations) > 1:
        initial_code = result.iterations[0].code
        diff_text    = compute_unified_diff(
            initial_code, result.final_code,
            "Round 0 — Initial Code",
            f"Round {result.rounds_count - 1} — Final Code"
        )
        lines += [
            "## 🔍 Code Evolution — Unified Diff",
            "",
            "```diff",
            diff_text,
            "```",
            "",
        ]

    # ── Final Code ───────────────────────────────────────────────
    lines += [
        "## 🏆 Final Approved Source Code",
        "",
        f"```{result.target_language}",
        result.final_code.strip(),
        "```",
        "",
    ]

    # ── Footer ───────────────────────────────────────────────────
    lines += [
        "---",
        "",
        "*Report generated by **OpenReviewAI v1.0.0** · "
        "Developed by Aman Varma · "
        "Druidot Consulting Pvt. Ltd. — Python Internship Project*",
        "",
    ]

    return "\n".join(lines)
